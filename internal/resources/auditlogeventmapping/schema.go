package auditlogeventmapping

import (
	"fmt"
	"strings"

	"github.com/hashicorp/terraform-plugin-framework-validators/setvalidator"
	"github.com/hashicorp/terraform-plugin-framework-validators/stringvalidator"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/planmodifier"
	"github.com/hashicorp/terraform-plugin-framework/resource/schema/stringplanmodifier"
	"github.com/hashicorp/terraform-plugin-framework/schema/validator"
	"github.com/hashicorp/terraform-plugin-framework/types"

	"github.com/fastly/go-fastly/v18/fastly/notifications/v1/eventmappings"
)

// ScopeTypes is the single source of truth for valid `scope_type` values.
var ScopeTypes = []string{
	eventmappings.ScopeTypeAccount,
	eventmappings.ScopeTypeVCL,
	eventmappings.ScopeTypeWasm,
	eventmappings.ScopeTypeNGWAF,
}

// ScopeTypesList renders ScopeTypes as a backtick-quoted list for descriptions,
// e.g. "`account`, `vcl`, `wasm`, or `ngwaf`".
func ScopeTypesList() string {
	quoted := make([]string, len(ScopeTypes))
	for i, t := range ScopeTypes {
		quoted[i] = fmt.Sprintf("`%s`", t)
	}
	return strings.Join(quoted[:len(quoted)-1], ", ") + ", or " + quoted[len(quoted)-1]
}

type Model struct {
	ID             types.String `tfsdk:"id"`
	Name           types.String `tfsdk:"name"`
	Description    types.String `tfsdk:"description"`
	ScopeType      types.String `tfsdk:"scope_type"`
	ScopeIDs       types.Set    `tfsdk:"scope_ids"`
	EventTypes     types.Set    `tfsdk:"event_types"`
	IntegrationIDs types.Set    `tfsdk:"integration_ids"`
	MappingStatus  types.String `tfsdk:"mapping_status"`
	CreatedAt      types.String `tfsdk:"created_at"`
	UpdatedAt      types.String `tfsdk:"updated_at"`
}

func ResourceAttributes() map[string]schema.Attribute {
	return map[string]schema.Attribute{
		"id": schema.StringAttribute{
			Computed:    true,
			Description: "The unique ID of the mapping, generated by Fastly.",
			PlanModifiers: []planmodifier.String{
				stringplanmodifier.UseStateForUnknown(),
			},
		},
		"name": schema.StringAttribute{
			Required:    true,
			Description: "Descriptive name for the mapping.",
			Validators: []validator.String{
				stringvalidator.LengthAtLeast(1),
			},
		},
		"description": schema.StringAttribute{
			Optional:    true,
			Description: "Description of the mapping.",
		},
		"scope_type": schema.StringAttribute{
			Required:    true,
			Description: fmt.Sprintf("The category of Fastly resource the mapping applies to. One of %s.", ScopeTypesList()),
			Validators: []validator.String{
				stringvalidator.OneOf(ScopeTypes...),
			},
		},
		"scope_ids": schema.SetAttribute{
			Optional:    true,
			ElementType: types.StringType,
			Description: "The specific service or workspace IDs to scope the mapping to. Omit to apply the mapping to all resources of the given `scope_type`. Must be empty when `scope_type` is `account`.",
		},
		"event_types": schema.SetAttribute{
			Required:    true,
			ElementType: types.StringType,
			Description: "The audit event types that trigger a notification. Each event type must be valid for the given `scope_type`.",
			Validators: []validator.Set{
				setvalidator.SizeAtLeast(1),
			},
		},
		"integration_ids": schema.SetAttribute{
			Required:    true,
			ElementType: types.StringType,
			Description: "The IDs of the integrations that should receive notifications. Must reference integrations belonging to the account linked to the configured token.",
			Validators: []validator.Set{
				setvalidator.SizeAtLeast(1),
			},
		},
		"mapping_status": schema.StringAttribute{
			Computed:    true,
			Description: "Whether the mapping is permitted to send notifications. One of `active` or `inactive`. A mapping is `active` as long as it has at least one integration ID.",
		},
		"created_at": schema.StringAttribute{
			Computed:    true,
			Description: "Timestamp (RFC3339) when the mapping was created.",
			PlanModifiers: []planmodifier.String{
				stringplanmodifier.UseStateForUnknown(),
			},
		},
		"updated_at": schema.StringAttribute{
			Computed:    true,
			Description: "Timestamp (RFC3339) when the mapping was last updated.",
		},
	}
}
